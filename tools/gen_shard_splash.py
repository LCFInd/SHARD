"""SHARD's power-on picture: the owner's artwork (assets/shard-splash-art.png, any size, square) on the FM-1's screen.
   python3 tools/gen_shard_splash.py   ->  assets/shard-splash.png (what the screen shows, 240 x 240)
                                           and firmware/src/shard_splash.h

The art is reduced to 240 x 240 and put in 16 colours: black up to the art's lightest warm grey in 15 steps, and its red.
The header holds it run-length coded, one byte a run: colour = b & 15, length = (b >> 4) + 1 (1..16), as DUO's
(LCFInd/DUO tools/gen_duo_splash.py). The firmware draws the version over the bottom right (ui_draw.c draw_splash)."""
import pathlib
from PIL import Image

ROOT = pathlib.Path(__file__).resolve().parent.parent
ART = ROOT / "assets" / "shard-splash-art.png"
OUT_PNG = ROOT / "assets" / "shard-splash.png"
OUT_H = ROOT / "firmware" / "src" / "shard_splash.h"
GREY = (178, 170, 165)                  # the art's lightest grey (its texture's top, a little warm)
RED = (200, 16, 20)                     # its rule
N = 15                                  # grey steps (black first); the red is colour 15


def palette():
    pal = [tuple(round(c * i / (N - 1)) for c in GREY) for i in range(N)]
    return pal + [RED]


def rgb565(c):
    r, g, b = c
    return (r >> 3) << 11 | (g >> 2) << 5 | b >> 3


def rle(px):
    out, i = [], 0
    while i < len(px):
        j = i
        while j + 1 < len(px) and px[j + 1] == px[i] and j - i < 15:
            j += 1
        out.append((j - i) << 4 | px[i])
        i = j + 1
    return out


def main():
    art = Image.open(ART).convert("RGB")
    sm = art.resize((240, 240), Image.LANCZOS)
    pal = palette()
    pim = Image.new("P", (1, 1))
    pim.putpalette([v for c in pal for v in c] + [0] * (768 - 3 * len(pal)))
    q = sm.quantize(palette=pim, dither=Image.Dither.NONE)
    q.convert("RGB").save(OUT_PNG)
    px = list(q.tobytes())
    runs = rle(px)
    assert sum((b >> 4) + 1 for b in runs) == 240 * 240
    lines = [", ".join(str(b) for b in runs[i:i + 40]) for i in range(0, len(runs), 40)]
    OUT_H.write_text(
        "/* SPDX-License-Identifier: GPL-3.0-only\n"
        " * Generated by tools/gen_shard_splash.py (assets/shard-splash-art.png; do not edit by hand): SHARD's power-on picture,\n"
        " * 240 x 240 in 16 colours, run-length coded: a byte a run, colour = b & 15, length = (b >> 4) + 1. */\n"
        f"static const uint16_t SHARD_SPLASH_PAL[16] = {{{', '.join(f'0x{rgb565(c):04X}' for c in pal)}}};\n"
        f"static const uint8_t SHARD_SPLASH[{len(runs)}] = {{\n    " + ",\n    ".join(lines) + "\n};\n")
    print(f"{OUT_H.relative_to(ROOT)}: {len(runs)} B; {OUT_PNG.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
