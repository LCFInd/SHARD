"""SHARD's curves (firmware/src/shard_tables.h), at 44.1 kHz: the engine has no floating point."""
import math, sys, os
FS = 44100
out = ["/* Generated by tools/gen_shard_tables.py. Do not edit. */", "#ifndef SHARD_TABLES_H", "#define SHARD_TABLES_H"]
def table(ctype, name, values, per=8):
    out.append(f"static const {ctype} {name}[{len(values)}] = {{")
    for i in range(0, len(values), per):
        out.append("    " + ", ".join(str(v) for v in values[i:i + per]) + ",")
    out.append("};")
# per-slice envelope: 0..127 -> 0.5 ms .. 8 s, per-sample steps of a 2^30 full scale
t = lambda i: 0.0005 * 16000 ** (min(i, 126) / 126)
table("uint32_t", "SHD_ENV_STEP", [max(1, round((1 << 30) / (t(i) * FS))) for i in range(128)])
# state-variable filter at 2x: cutoff 0..127 -> 30 Hz .. 16 kHz (f, Q14); resonance 0..127 -> damping 2.0 .. 0.08 (Q14)
hz = lambda i: 30 * (16000 / 30) ** (i / 127)
table("int32_t", "SHD_SVF_F", [round(16384 * 2 * math.sin(math.pi * hz(i) / (2 * FS))) for i in range(128)])
table("int32_t", "SHD_SVF_Q", [round(16384 * (2.0 - 1.92 * (i / 127) ** 0.7)) for i in range(128)])
# the damping's ceiling per cutoff: the Chamberlin filter is stable only while f q < 2 and f^2 + 2 f q < 4 (each of
# the two steps a sample); near the top a low RES broke both (CUT 127, RES 0: f q 2.16, a sine came out clipped at
# 3x). With a margin (f q <= 1.6, f^2 + 2 f q <= 3.4) the top 9 cutoffs take less damping; below, the table is 2.0
svf_f = [2 * math.sin(math.pi * hz(i) / (2 * FS)) for i in range(128)]
table("int32_t", "SHD_SVF_QMAX", [min(32768, int(16384 * min(1.6 / f, (3.4 - f * f) / (2 * f)))) for f in
                                  [round(16384 * x) / 16384 for x in svf_f]])
# band split one-poles: 0..127 -> 40 Hz .. 12 kHz (Q15)
xo = lambda i: 40 * (12000 / 40) ** (i / 127)
table("int32_t", "SHD_ONEPOLE", [round(32768 * (1 - math.exp(-2 * math.pi * xo(i) / FS))) for i in range(128)])
# drive: x1 .. x64 (Q8), make-up gain ~ g^-0.4 (Q15)
g = [64 ** (i / 127) for i in range(128)]
table("int32_t", "SHD_DRIVE_Q8", [round(256 * x) for x in g])
table("int32_t", "SHD_MAKEUP", [round(32767 * x ** -0.4) for x in g])
# gate threshold 0..127 -> off, -90 .. -6 dBFS (Q15)
table("int32_t", "SHD_GATE_Q15", [0] + [max(1, round(32767 * 10 ** ((-90 + 84 * i / 127) / 20))) for i in range(1, 128)])
# sustain 0..127 -> the envelope's floor: sqrt(level) of 2^30 (its gain is the square)
table("uint32_t", "SHD_SUS_ENV", [round((1 << 30) * math.sqrt(i / 127)) for i in range(128)])
# comb filters: CUT 0..127 -> 90 Hz .. 6 kHz, the delay in Q8 samples (at most SHD_COMB - 2); RES 0..127 -> feedback
# 0 .. 0.96 (Q15)
ch = lambda i: 90 * (6000 / 90) ** (i / 127)
table("uint32_t", "SHD_COMB_D", [min(510 * 256, round(256 * FS / ch(i))) for i in range(128)])
table("int32_t", "SHD_COMB_G", [round(32768 * 0.96 * (i / 127) ** 0.8) for i in range(128)])
# the analog shapers (eng_shard.c shd_tube / shd_rat / shd_war): one-pole coefficients (Q15) at 44.1 kHz
a1 = lambda f: round(32768 * (1 - math.exp(-2 * math.pi * f / FS)))
for name, f in [("20", 20), ("60", 60), ("80", 80), ("120", 120), ("200", 200), ("400", 400), ("1100", 1100),
                ("1539", 1539), ("4500", 4500), ("5500", 5500), ("9000", 9000)]:
    out.append(f"#define SHD_A{name} {a1(f)}")
# OVRDRV (a 12AX7 stage): gain x1 .. x48 (Q8); its Miller roll-off 9 kHz .. 4.5 kHz
dn = [i / 127 for i in range(128)]
table("int32_t", "SHD_TUBE_G", [round(256 * 48 ** d) for d in dn])
table("int32_t", "SHD_TUBE_LP", [a1(9000 * 0.5 ** d) for d in dn])
# DIST (a RAT): DISTORTION's 100 k log pot: R 0 .. 100 k; the op-amp's legs to ground: 47 R + 2.2 uF (1.5 kHz) and
# 560 R + 4.7 uF (60 Hz): their gains R / 47 and R / 560 (Q8); the LM308's bandwidth, GBW / gain, 20 kHz .. 2.5 kHz
R = [100000 * d ** 2.4 for d in dn]
table("int32_t", "SHD_RAT_HI", [round(256 * r / 47) for r in R])
table("int32_t", "SHD_RAT_LO", [round(256 * r / 560) for r in R])
table("int32_t", "SHD_RAT_LP", [a1(max(2500, min(20000, 1.6e6 / (1 + r / 47)))) for r in R])
# FUZZ (a Fuzz War: gain stages, a Muff-style tone stack, a clipping stage): each of three stages x1 .. x14 (Q8),
# x2700 in all; the sputter gate's threshold (Q15) rising with the gain
table("int32_t", "SHD_WAR_G", [round(256 * 14 ** d) for d in dn])
table("int32_t", "SHD_WAR_TH", [round(1800 * d ** 2) for d in dn])
# DECK MODE (deck.c): a band's level 0..127 -> KILL (0), -40 .. 0 dB (1 .. 64, 0 dB at 64), 0 .. +6 dB (64 .. 127), as
# a gain (Q14) and as shown (0.1 dB); the crossovers' frequencies as shown (Hz, the split one-poles' xo)
deck_db = lambda i: -40 * (64 - i) / 63 if i <= 64 else 6 * (i - 64) / 63
table("int32_t", "DECK_GAIN_Q14", [0] + [16384 if i == 64 else round(16384 * 10 ** (deck_db(i) / 20)) for i in range(1, 128)])
table("int16_t", "DECK_GAIN_DB10", [-999] + [round(10 * deck_db(i)) for i in range(1, 128)])
table("uint16_t", "DECK_XO_HZ", [round(xo(i)) for i in range(128)])
# the crossfader (fx.c mix_part): deck A's gain at position i (XFADE + 64; deck B's: at 127 - i), Q15, for each CURVE:
# SMOOTH (both at full in the middle, each down to 0 over its own half), DJ (equal power: -3 dB in the middle), CUT
# (a scratch curve: full until the last 1/16 of the travel). (XFADE 0 is i = 64: SMOOTH x 2.02 keeps it full there)
xf = [lambda x: min(1.0, 2.02 * (1 - x)), lambda x: math.cos(x * math.pi / 2), lambda x: min(1.0, max(0.0, (1 - x) * 16))]
table("int16_t", "DECK_XF_Q15", [min(32767, round(32767 * f(i / 127))) for f in xf for i in range(128)])
# the ISOLATE page's analyzer (ui_graph.c graph_deck_iso): 20 bands 50 Hz .. 12 kHz, each a Goertzel over the last
# 256 samples: its coefficient 2 cos(w) (Q14) and the band's centre (Hz); a Hann window (Q15)
gz = [50 * (12000 / 50) ** (k / 19) for k in range(20)]
table("int16_t", "DECK_GZ_C", [round(16384 * 2 * math.cos(2 * math.pi * f / FS)) for f in gz])
table("uint16_t", "DECK_GZ_HZ", [round(f) for f in gz])
table("uint16_t", "DECK_HANN", [round(32767 * 0.5 * (1 - math.cos(2 * math.pi * i / 255))) for i in range(256)])
# the crossovers' one-poles, trapezoidal (TPT: 2 LP - x is an exact all-pass, so the bands add up flat): G = g / (1 + g),
# g = tan(pi f / fs) (Q15)
table("int32_t", "DECK_TPT_G", [round(32768 * math.tan(math.pi * xo(i) / FS) / (1 + math.tan(math.pi * xo(i) / FS)))
                               for i in range(128)])
# MASTER EQ (fx.c meq): -12 .. +12 dB -> A^2 - 1 (Q14; A = 10^(dB/40)). The shelves: TPT one-poles (Q15), a cut the
# exact inverse of the boost (its corner moved by the gain: 150 Hz x, 5 kHz / 10^(|dB|/20)). The bell at MID F (the
# crossovers' 40 Hz .. 12 kHz, DECK_XO_HZ): a TPT state-variable filter, Q 0.9, constant-Q in dB both ways (k = 1 /
# (Q A)): tan(pi f / FS) (Q16) here, k (Q16) by the gain; a1 .. a3 each block (meq_block)
table("int32_t", "MEQ_A_Q14", [round(16384 * (10 ** (db / 20) - 1)) for db in range(-12, 13)])
G1 = lambda f: math.tan(math.pi * f / FS) / (1 + math.tan(math.pi * f / FS))
B = lambda db: 10 ** (abs(db) / 20)
table("int32_t", "MEQ_LO_G", [round(32768 * G1(150 * (B(db) if db < 0 else 1))) for db in range(-12, 13)])
table("int32_t", "MEQ_HI_G", [round(32768 * G1(5000 / (B(db) if db < 0 else 1))) for db in range(-12, 13)])
MEQ_Q = 0.9
table("int32_t", "MEQ_G16", [round(65536 * math.tan(math.pi * xo(i) / FS)) for i in range(128)])
table("int32_t", "MEQ_K16", [round(65536 / (MEQ_Q * 10 ** (db / 40))) for db in range(-12, 13)])
# .. its picture (ui_graph.c graph_meq): each band's share of its gain in dB (Q8) on the analyzer's scale (8 a
# octave from 50 Hz, 64 steps): the shelves by position, the bell by its distance from MID F
def db(h): return 20 * math.log10(abs(h))
def shelf(f, fc, lo):
    s = 1j * f / fc
    return (1 / (1 + s)) if lo else (s / (1 + s))
fx = lambda u: 50 * 2 ** (u / 8)
A4 = 10 ** (12 / 20)                               # (the share at +12 dB, as the device does it)
table("int16_t", "MEQ_SH_LO", [round(256 * db(1 + (A4 - 1) * shelf(fx(u), 150, 1)) / 12) for u in range(64)])
table("int16_t", "MEQ_SH_HI", [round(256 * db(1 + (A4 - 1) * shelf(fx(u), 5000, 0)) / 12) for u in range(64)])
def bell(d):
    r, a = 2 ** (d / 8), 10 ** (12 / 40)
    bp = 1 / (1 + 1j * MEQ_Q * a * (r - 1 / r))      # (k = 1 / (Q A): the band-pass, 1 at MID F)
    return round(256 * db(1 + (A4 - 1) * bp) / 12)
table("int16_t", "MEQ_BELL", [bell(d) for d in range(64)])
out.append("#endif")
path = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(__file__), "..", "firmware", "src", "shard_tables.h")
open(path, "w").write("\n".join(out) + "\n")
print("shard tables ->", path)
