"""SHARD's curves (firmware/src/shard_tables.h), at 44.1 kHz: the engine has no floating point."""
import math, sys, os
FS = 44100
out = ["/* Generated by tools/gen_shard_tables.py. Do not edit. */", "#ifndef SHARD_TABLES_H", "#define SHARD_TABLES_H"]
def table(ctype, name, values, per=8):
    out.append(f"static const {ctype} {name}[{len(values)}] = {{")
    for i in range(0, len(values), per):
        out.append("    " + ", ".join(str(v) for v in values[i:i + per]) + ",")
    out.append("};")
# per-slice envelope: 0..127 -> 0.5 ms .. 8 s, per-sample steps of a 2^30 full scale
t = lambda i: 0.0005 * 16000 ** (min(i, 126) / 126)
table("uint32_t", "SHD_ENV_STEP", [max(1, round((1 << 30) / (t(i) * FS))) for i in range(128)])
# state-variable filter at 2x: cutoff 0..127 -> 30 Hz .. 16 kHz (f, Q14); resonance 0..127 -> damping 2.0 .. 0.08 (Q14)
hz = lambda i: 30 * (16000 / 30) ** (i / 127)
table("int32_t", "SHD_SVF_F", [round(16384 * 2 * math.sin(math.pi * hz(i) / (2 * FS))) for i in range(128)])
table("int32_t", "SHD_SVF_Q", [round(16384 * (2.0 - 1.92 * (i / 127) ** 0.7)) for i in range(128)])
# band split one-poles: 0..127 -> 40 Hz .. 12 kHz (Q15)
xo = lambda i: 40 * (12000 / 40) ** (i / 127)
table("int32_t", "SHD_ONEPOLE", [round(32768 * (1 - math.exp(-2 * math.pi * xo(i) / FS))) for i in range(128)])
# drive: x1 .. x64 (Q8), make-up gain ~ g^-0.4 (Q15)
g = [64 ** (i / 127) for i in range(128)]
table("int32_t", "SHD_DRIVE_Q8", [round(256 * x) for x in g])
table("int32_t", "SHD_MAKEUP", [round(32767 * x ** -0.4) for x in g])
# gate threshold 0..127 -> off, -90 .. -6 dBFS (Q15)
table("int32_t", "SHD_GATE_Q15", [0] + [max(1, round(32767 * 10 ** ((-90 + 84 * i / 127) / 20))) for i in range(1, 128)])
# sustain 0..127 -> the envelope's floor: sqrt(level) of 2^30 (its gain is the square)
table("uint32_t", "SHD_SUS_ENV", [round((1 << 30) * math.sqrt(i / 127)) for i in range(128)])
# comb filters: CUT 0..127 -> 90 Hz .. 6 kHz, the delay in Q8 samples (at most SHD_COMB - 2); RES 0..127 -> feedback
# 0 .. 0.96 (Q15)
ch = lambda i: 90 * (6000 / 90) ** (i / 127)
table("uint32_t", "SHD_COMB_D", [min(510 * 256, round(256 * FS / ch(i))) for i in range(128)])
table("int32_t", "SHD_COMB_G", [round(32768 * 0.96 * (i / 127) ** 0.8) for i in range(128)])
out.append("#endif")
path = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(__file__), "..", "firmware", "src", "shard_tables.h")
open(path, "w").write("\n".join(out) + "\n")
print("shard tables ->", path)
